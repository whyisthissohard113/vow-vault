      expect(retry.reset).toBe(1);

      const [resetJob] = await db
        .select()
        .from(mediaProcessingJobs)
        .where(eq(mediaProcessingJobs.id, contentHashJob!.id))
        .limit(1);
      expect(resetJob!.status).toBe("pending");
      expect(resetJob!.attempts).toBe(0);
      expect(resetJob!.errorMessage).toBeNull();

      await drainJobs(mediaId, storage);

      const [completedJob] = await db
        .select({ status: mediaProcessingJobs.status })
        .from(mediaProcessingJobs)
        .where(eq(mediaProcessingJobs.id, contentHashJob!.id))
        .limit(1);
