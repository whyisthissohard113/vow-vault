/** Minimal valid JPEG (generated by sharp at test time). */
async function makeJpeg(): Promise<Buffer> {
  return sharp({
    create: {
      width: 4,
      height: 4,
      channels: 3,
      background: { r: 220, g: 30, b: 40 },
    },
  })
    .jpeg({ quality: 80 })
    .toBuffer();
}

/** Minimal ISO-BMFF container accepted as video/mp4 (ftyp isom). */
function makeMinimalMp4(): Buffer {
  // Top-level ftyp box: size 24 + "ftyp" + major brand + minor + compatible brands.
  const buf = Buffer.alloc(24);
  buf.writeUInt32BE(24, 0);
  buf.write("ftyp", 4, "latin1");
  buf.write("isom", 8, "latin1");
  buf.writeUInt32BE(0, 12);
  buf.write("isom", 16, "latin1");
  buf.write("mp42", 20, "latin1");
  return buf;
}

