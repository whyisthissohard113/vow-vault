/** Runs every pending job for a media item until none remain (worker simulation). */
async function drainJobs(mediaId: string, storage: StorageClient): Promise<void> {
  let guard = 0;
  for (;;) {
    guard += 1;
    if (guard > 30) throw new Error("drainJobs did not converge");

    const jobs = await db
      .select()
      .from(mediaProcessingJobs)
      .where(eq(mediaProcessingJobs.mediaId, mediaId));

    const pending = jobs.filter((j) => j.status === "pending");
    if (pending.length === 0) {
      await maybeMarkMediaProcessed(mediaId);
      return;
    }
    for (const job of pending) {
      await executeMediaJob(job.id, storage);
    }
  }
}

